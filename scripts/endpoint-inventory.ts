/**
 * Security inventory of every registered API endpoint, generated from the route definitions
 * themselves (the same objects Express mounts), so it cannot drift from the code.
 *
 *   npm run security:inventory            # writes docs/audit/ENDPOINT_INVENTORY.md
 *   npm run security:inventory -- --json  # prints JSON instead
 *
 * Needs no database and never reads .env (it runs with NODE_ENV=test and dummy settings).
 */
process.env.NODE_ENV = 'test';
process.env.MONGODB_URI ??= 'mongodb://127.0.0.1:1/inventory-not-connected';
process.env.JWT_ACCESS_SECRET ??= 'inventory-access-secret-not-used-0123456789';
process.env.JWT_PLATFORM_SECRET ??= 'inventory-platform-secret-not-used-012345678';

import fs from 'node:fs';
import path from 'node:path';

export interface InventoryRow {
  method: string;
  path: string;
  auth: 'public' | 'school' | 'platform';
  permissions: string[];
  roles: string[];
  platformRoles: string[];
  params: boolean;
  query: boolean;
  body: boolean;
  upload: boolean;
  produces?: string;
  rateLimits: string[];
  tenant: 'token' | 'platform-global' | 'none';
  sensitivity: string[];
}

const SENSITIVE: Array<[RegExp, string]> = [
  [/\/(fees|invoices|payments|payslips|accounts\/|income|expense|ledger|outstanding)/, 'financial'],
  [/\/(students|parents|admissions|employees|users|attendance|marks|results|homework|certificates)/, 'personal'],
  [/\/files|\/documents|upload|\/download/, 'files'],
  [/\/(export|\.csv)|csv/, 'export'],
  [/\/backups/, 'backup'],
  [/\/(roles|permissions|admins|access-link|status|suspend|subscription|plan|feature-overrides)/, 'administrative'],
  [/\/auth\//, 'authentication'],
];

export async function collectInventory(): Promise<InventoryRow[]> {
  const { Api } = await import('../src/utils/api');
  const limits = await import('../src/middleware/rate-limit');
  const named = new Map<unknown, string>(Object.entries(limits).map(([k, v]) => [v, k]));
  const rows: InventoryRow[] = [];
  const original = Api.prototype.route;
  Api.prototype.route = function capture(this: InstanceType<typeof Api>, def: any) {
    const full = (this.prefix + def.path).replace(/\/$/, '') || '/';
    const rateLimits = ['globalLimiter', ...(def.middleware ?? []).map((m: unknown) => named.get(m) ?? 'custom')];
    const sensitivity = SENSITIVE.filter(([rx]) => rx.test(full) || (def.produces && rx.test(def.produces))).map(
      ([, s]) => s,
    );
    if (def.produces === 'text/csv' && !sensitivity.includes('export')) sensitivity.push('export');
    rows.push({
      method: def.method.toUpperCase(),
      path: full,
      auth: def.auth,
      permissions: def.permission ? [].concat(def.permission) : [],
      roles: def.roles ?? [],
      platformRoles: def.platformRoles ?? [],
      params: !!def.params,
      query: !!def.query,
      body: !!def.body,
      upload: !!def.upload,
      produces: def.produces,
      rateLimits,
      tenant: def.auth === 'school' ? 'token' : def.auth === 'platform' ? 'platform-global' : 'none',
      sensitivity: [...new Set(sensitivity)],
    });
    return original.call(this, def);
  };
  try {
    const { buildApis } = await import('../src/app');
    buildApis();
  } finally {
    Api.prototype.route = original;
  }
  return rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

function toMarkdown(rows: InventoryRow[]): string {
  const count = (a: InventoryRow['auth']) => rows.filter((r) => r.auth === a).length;
  const yes = (b: boolean) => (b ? 'Y' : '');
  const out = [
    '# Endpoint security inventory',
    '',
    'Generated by `npm run security:inventory` from the route definitions that Express mounts ' +
      '(`src/utils/api.ts`). Do not edit by hand; regenerate after changing routes.',
    '',
    `Total: **${rows.length}** endpoints — public ${count('public')}, school ${count('school')}, platform ${count('platform')}.`,
    '',
    'How to read it:',
    '- **Auth** `school`: bearer token verified, user + school re-loaded from the database on every request; the tenant (`schoolId`) comes only from the verified token. `platform`: separate secret/audience and collection. `public`: no token.',
    '- **Permissions / roles**: enforced server-side before the handler runs. Routes with neither still require an authenticated active user; many apply per-record checks inside the handler (e.g. teacher/parent scope in `academics/access.service.ts`).',
    '- **Validated**: P/Q/B = params/query/body schema (Zod) parsed before the handler; unknown keys are stripped. U = multipart upload (type sniffed, size-limited).',
    '- **Rate limits**: `globalLimiter` applies to every route; others are route-specific.',
    '- **Sensitivity**: keyword heuristic on the path, for prioritising review — not an access rule.',
    '- Tenant isolation is additionally enforced at the data layer: every tenant collection rejects queries without a `schoolId` filter (`database/tenant-plugin.ts`).',
    '',
    '| Method | Path | Auth | Permissions / roles | Validated | Rate limits | Sensitivity |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const access = [
      ...r.permissions.map((p) => `\`${p}\``),
      ...r.roles.map((x) => `role:${x}`),
      ...r.platformRoles.map((x) => `platform:${x}`),
    ].join(' ');
    const validated = [r.params && 'P', r.query && 'Q', r.body && 'B', r.upload && 'U'].filter(Boolean).join('');
    out.push(
      `| ${r.method} | \`${r.path}\` | ${r.auth} | ${access || (r.auth === 'public' ? '—' : 'authenticated')} | ${validated || yes(false)} | ${r.rateLimits.filter((l) => l !== 'globalLimiter').join(', ') || 'global'} | ${r.sensitivity.join(', ')} |`,
    );
  }
  return out.join('\n') + '\n';
}

if (require.main === module) {
  collectInventory()
    .then((rows) => {
      if (process.argv.includes('--json')) {
        process.stdout.write(JSON.stringify(rows, null, 2));
        return;
      }
      const file = path.join(__dirname, '..', 'docs', 'audit', 'ENDPOINT_INVENTORY.md');
      fs.writeFileSync(file, toMarkdown(rows));
      console.log(`Wrote ${rows.length} endpoints to ${path.relative(process.cwd(), file)}`);
      process.exit(0);
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
